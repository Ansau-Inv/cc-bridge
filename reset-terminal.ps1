# 复位终端的鼠标追踪 / 备用屏模式。
#
# ════════════════════════════════════════════════════════════════════
# 什么时候需要它
# ════════════════════════════════════════════════════════════════════
#
# dsh-TUI 进全屏时往终端写这一串（mouse-debug.log 里的实证）：
#
#   \x1b[?1049h  \x1b[2J \x1b[H  \x1b[?1000h \x1b[?1002h \x1b[?1003h \x1b[?1006h
#    备用屏                       按键     拖动     任何移动    SGR编码
#
# 撤销序列（`\x1b[?1006l ?1003l ?1002l ?1000l ?1049l`）**只在优雅退出时**
# 才写出去 —— ink 里挂在 `signal-exit` 的 `onExit` 上（ink.js 的 `unmount`）。
#
# 所以进程被 `Stop-Process -Force` / `taskkill /F` 强杀时，撤销代码
# **永远不会执行**，终端就留在鼠标追踪模式里：鼠标一移动，终端就往
# 输入流里注入 `\x1b[<35;col;rowM` 这类 SGR 序列，看起来就是
# **「输入变成了 ANSI 符号」**。
#
# 解法：手动把这些模式关掉。往终端写撤销序列即可。
#
# ════════════════════════════════════════════════════════════════════
# 怎么用
# ════════════════════════════════════════════════════════════════════
#
#   # 在**卡住的那个窗口里**执行（必须是那个终端本身）
#   pwsh -File reset-terminal.ps1
#
# 注意：这个脚本修的是**它自己所在的那个终端**。从别的窗口跑没用 ——
# 转义序列是写给当前 stdout 的。所以卡住时要在那个窗口敲。
#
# 如果那个窗口已经完全没法输入了，最快的办法是：
#   · 关掉那个 tab 重新开（WT 会重置该 tab 的模式）
#   · 或者用 `Ctrl+Shift+P` → 重新打开

[CmdletBinding()]
param(
  # 只关鼠标追踪，不动备用屏（默认两个都复位）
  [switch]$MouseOnly
)

# ── 要复位的模式 ────────────────────────────────────────────────────
#
# 编号含义（dsh-tui 的 ink/termio/dec.js 里有同样的常量表）：
#   1000  鼠标：按键按下/抬起/滚轮
#   1002  鼠标：拖动（按住时的移动）
#   1003  鼠标：任何移动（hover 用这个）
#   1004  焦点事件上报
#   1006  SGR 编码（CSI < btn;col;row M/m，取代老的 X10 编码）
#   2004  括号粘贴（bracketed paste）
#   1049  备用屏（进入时保存主屏并清屏，退出时还原）
#   25    光标显示（TUI 会藏起来，卡住时也一起恢复）
$modes = @(1006, 1003, 1002, 1000, 1004, 2004)
if (-not $MouseOnly) {
  # 1049 放最后：先把鼠标焦点这些关掉，再切回主屏
  $modes += 1049
}

# CSI ? <n> l  = DECRESET
$seq = ($modes | ForEach-Object { "$([char]27)[?$($_)l" }) -join ''
# 再把光标显示出来（DECTCEM set，即 \x1b[?25h）
$seq += "$([char]27)[?25h"

# 有些终端对「一次性写一大串」处理得不好，逐个写更稳
foreach ($m in $modes) {
  [Console]::Out.Write("$([char]27)[?${m}l")
  [Console]::Out.Flush()
}
[Console]::Out.Write("$([char]27)[?25h")
[Console]::Out.Flush()

# 换行并清掉可能残留的半行（鼠标序列可能已经污染了输入回显）
[Console]::Out.Write("`r`n")
[Console]::Out.Flush()

Write-Host '终端模式已复位：' -NoNewline -ForegroundColor Green
Write-Host ("鼠标追踪(1000/1002/1003/1006)、焦点上报(1004)、括号粘贴(2004)" +
  $(if (-not $MouseOnly) { '、备用屏(1049)' } else { '' }) + '、光标显示')
Write-Host '如果鼠标一动还是会吐字符，说明跑在了错误的窗口 —— 请在卡住的那个终端里执行。' -ForegroundColor DarkGray
